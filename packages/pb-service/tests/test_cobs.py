"""COBS framing for the USB transport.

The vectors here were captured from an Inventor hub running v4.1.0b3 rather
than generated by this implementation, because a codec checked against itself
proves only that it is self-consistent. The hub-to-host frames were encoded by
the firmware, and the host-to-hub frames are ones the firmware accepted and
answered correctly, so both directions are pinned by something other than us.
"""

from __future__ import annotations

import pytest

from pb_service.hub.stream import cobs

SUBSCRIBE = 1
READ = 3
EVENT = 2
READ_REPLY = 3

GATT = 0x01
PYBRICKS = 0x02


# ------------------------------------------------------- captured from a hub


@pytest.mark.parametrize(
    ("wire", "message_type", "payload"),
    [
        # Requests the hub accepted and answered.
        ("54 54 00 02", SUBSCRIBE, bytes([1])),
        ("5b 00 00 07 29 02", READ, bytes([GATT, 0x00, 0x2A])),
        ("5b 00 06 25 29 02", READ, bytes([GATT, 0x26, 0x2A])),
        ("5b 00 06 2b 29 02", READ, bytes([GATT, 0x28, 0x2A])),
        ("5b 00 06 53 29 02", READ, bytes([GATT, 0x50, 0x2A])),
        ("af 00 07 00 00 02", READ, bytes([PYBRICKS, 0x03, 0x00])),
    ],
)
def test_encodes_what_the_hub_accepted(
    wire: str, message_type: int, payload: bytes
) -> None:
    assert cobs.encode(message_type, payload) == bytes.fromhex(wire)


@pytest.mark.parametrize(
    ("wire", "message_type", "payload"),
    [
        # Replies the firmware encoded, delimiter already stripped.
        (
            "5b 00 00 13 29 53 7a 61 71 6a 60 68 70 23 4b 76 61",
            READ_REPLY,
            bytes([GATT, 0x00, 0x2A]) + b"Pybricks Hub",
        ),
        (
            "5b 00 0f 25 29 37 2d 32 2d 33 61 30",
            READ_REPLY,
            bytes([GATT, 0x26, 0x2A]) + b"4.1.0b3",
        ),
        (
            "5b 00 09 2b 29 32 2d 35 2d 33",
            READ_REPLY,
            bytes([GATT, 0x28, 0x2A]) + b"1.6.0",
        ),
        # A status report: event type 0, then the flags little-endian. This one
        # has BLE_ADVERTISING (bit 3) and USB_HOST_CONNECTED (bit 12) set.
        (
            "a8 00 06 0b 13 00 00 00 00",
            EVENT,
            bytes([0x00, 0x08, 0x10, 0x00, 0x00, 0x00, 0x00]),
        ),
    ],
)
def test_decodes_what_the_hub_sent(
    wire: str, message_type: int, payload: bytes
) -> None:
    assert cobs.decode(bytes.fromhex(wire)) == (message_type, payload)


def test_a_captured_reply_round_trips() -> None:
    # Encoding what the firmware sent must reproduce the firmware's own bytes,
    # which is the strongest single check available without a hub.
    wire = bytes.fromhex("5b 00 09 2b 29 32 2d 35 2d 33")
    frame = cobs.decode(wire)

    assert frame is not None
    assert cobs.encode(frame.type, frame.payload) == wire + bytes([cobs.DELIMITER])


# --------------------------------------------------------------- properties


PAYLOADS = [
    pytest.param(b"\x01", id="one-escaped-byte"),
    pytest.param(b"\x00\x01\x02", id="every-escaped-value"),
    pytest.param(b"\x00" * 200, id="nothing-but-zeros"),
    pytest.param(b"\x02" * 100, id="nothing-but-delimiters"),
    pytest.param(bytes(range(256)), id="every-byte-value"),
    pytest.param(bytes(range(256)) * 4, id="a-thousand-bytes"),
    pytest.param(b"\xff" * 83, id="one-byte-short-of-a-block"),
    pytest.param(b"\xff" * 84, id="exactly-one-block"),
    pytest.param(b"\xff" * 85, id="one-byte-over-a-block"),
    pytest.param(b"\xff" * 83 + b"\x00", id="a-full-block-ended-by-an-escaped-value"),
    pytest.param(b"x", id="one-ordinary-byte"),
]


@pytest.mark.parametrize("payload", PAYLOADS)
@pytest.mark.parametrize("message_type", [0x00, 0x01, 0x02, 0x03, 0xFF])
def test_round_trips(message_type: int, payload: bytes) -> None:
    wire = cobs.encode(message_type, payload)

    assert cobs.decode(wire[:-1]) == (message_type, payload)


@pytest.mark.parametrize("payload", PAYLOADS)
def test_the_body_never_contains_a_delimiter_or_the_xor_value(payload: bytes) -> None:
    body = cobs.encode(0x03, payload)[:-1]

    # 0x01 and 0x02 delimit, and the XOR exists to keep 0x03 out as well. Any
    # of the three appearing in a body would break framing for every message
    # after it, which is the failure that is hardest to see.
    assert not set(body) & {0x01, 0x02, 0x03}


@pytest.mark.parametrize("payload", PAYLOADS)
def test_every_frame_ends_with_the_delimiter(payload: bytes) -> None:
    wire = cobs.encode(0x03, payload)

    assert wire[-1] == cobs.DELIMITER
    assert wire.count(cobs.DELIMITER) == 1


def test_the_delimiter_is_not_the_classic_zero() -> None:
    # Worth pinning: every other COBS implementation frames on 0x00, and taking
    # one off a shelf would produce a hub that never answers.
    assert cobs.DELIMITER == 0x02


# ------------------------------------------------------------ malformed input


def test_a_leading_high_priority_delimiter_is_tolerated() -> None:
    # The firmware never emits one but accepts it, so a host that receives one
    # has to as well.
    wire = cobs.encode(READ_REPLY, bytes([GATT, 0x28, 0x2A]))
    body = wire[:-1]

    assert cobs.decode(bytes([0x01]) + body) == cobs.decode(body)


@pytest.mark.parametrize("body", [b"", b"\x01", b"\x00"])
def test_an_empty_or_stunted_frame_is_not_a_message(body: bytes) -> None:
    assert cobs.decode(body) is None


def test_a_frame_carrying_only_a_type_is_not_a_message() -> None:
    # Every message defined today has a payload, so one without is malformed
    # rather than an empty message, and the firmware treats it the same way.
    assert cobs.decode(cobs.encode(READ)[:-1]) is None
